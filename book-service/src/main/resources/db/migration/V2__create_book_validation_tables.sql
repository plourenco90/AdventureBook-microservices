CREATE TABLE book_validation
(
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL,

    CONSTRAINT fk_book_validation_book
        FOREIGN KEY (book_id)
            REFERENCES books (id)
            ON DELETE CASCADE,

    CONSTRAINT uk_book_validate_book
        UNIQUE (book_id)
);


CREATE TABLE book_validation_error
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    validation_id BIGINT       NOT NULL,
    code          VARCHAR(64)  NULL,
    message       VARCHAR(255) NULL,
    section_id    BIGINT       NULL,

    CONSTRAINT fk_book_validation_error_validation
        FOREIGN KEY (validation_id)
            REFERENCES book_validation (id)
            ON DELETE CASCADE
);