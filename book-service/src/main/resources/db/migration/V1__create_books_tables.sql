CREATE TABLE books
(
    id     BIGINT PRIMARY KEY,
    title  VARCHAR(255) NOT NULL,
    author VARCHAR(255) NOT NULL
);

CREATE TABLE book_sections
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id    BIGINT      NOT NULL,
    section_id INTEGER     NOT NULL,
    text       TEXT        NOT NULL,
    type       VARCHAR(20) NOT NULL,

    CONSTRAINT fk_book_sections_book
        FOREIGN KEY (book_id)
            REFERENCES books (id)
            ON DELETE CASCADE,

    CONSTRAINT uk_book_sections_book_section
        UNIQUE (book_id, section_id)
);

CREATE TABLE section_options
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id        BIGINT  NOT NULL,
    option_index      INTEGER NOT NULL,
    description       TEXT    NOT NULL,
    target_section_id INTEGER NOT NULL,

    CONSTRAINT fk_section_options_section
        FOREIGN KEY (section_id)
            REFERENCES book_sections (id)
            ON DELETE CASCADE,

    CONSTRAINT uk_section_options_index
        UNIQUE (section_id, option_index)
);

CREATE TABLE option_consequences
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    option_id BIGINT      NOT NULL,
    type      VARCHAR(50) NOT NULL,
    value     INTEGER     NOT NULL,
    text      TEXT,

    CONSTRAINT fk_option_consequences_option
        FOREIGN KEY (option_id)
            REFERENCES section_options (id)
            ON DELETE CASCADE
);

CREATE INDEX idx_book_sections_book_id
    ON book_sections (book_id);

CREATE INDEX idx_section_options_section_id
    ON section_options (section_id);